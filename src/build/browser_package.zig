//! Build-time generator for the browser SDK npm package (D14).
//!
//! Produces the generated TypeScript modules consumed by the hand-written
//! SDK sources (src/clients/browser/src/generated/):
//!   - tables.ts — FeatureID / FeatureType const tables + types,
//!     derived from model (single source of truth; kills the hand-synced
//!     duplicates),
//!   - config.ts — SDK_VERSION (from package.json) and
//!     DEFAULT_INGRESS_URL (--ingress-url build option / FINGERPRINT_INGRESS_URL
//!     env / built-in default).
//!
//! `tsc` then compiles the TS sources into dist/ (the documented Node
//! exception, D13). There is no wasm, no base64-inlined bundle, and no
//! fingerprint computation anywhere in the package — the browser only emits
//! a versioned SignalPackage (DESIGN §9.4).
//!
//! The run step has no captured outputs, so the build runner treats it as
//! side-effecting and executes it on every invocation (it rewrites
//! generated/ in the source tree).
const std = @import("std");
const model = @import("model");

const usage =
    \\usage: browser_package <package.json> <ingress-url> <package-dir>
    \\
;

pub fn main() !void {
    var gpa = std.heap.GeneralPurposeAllocator(.{}){};
    defer _ = gpa.deinit();
    const alloc = gpa.allocator();

    const args = try std.process.argsAlloc(alloc);
    defer std.process.argsFree(alloc, args);
    if (args.len != 4) {
        std.debug.print("{s}", .{usage});
        std.process.exit(1);
    }

    const package_json_path = args[1];
    const ingress_url = args[2];
    const package_dir = args[3];

    // 1. Read the package version.
    const pkg_json = try std.fs.cwd().readFileAlloc(alloc, package_json_path, 1 << 16);
    defer alloc.free(pkg_json);
    const version = try packageVersion(alloc, pkg_json);
    defer alloc.free(version);

    // 2. Write generated/tables.ts (FeatureID / FeatureType from the model).
    const tables = try buildTables(alloc);
    defer alloc.free(tables);
    try writeGenerated(alloc, package_dir, "tables.ts", tables);

    // 3. Write generated/config.ts (version + ingress URL).
    const config = try buildConfig(alloc, version, ingress_url);
    defer alloc.free(config);
    try writeGenerated(alloc, package_dir, "config.ts", config);

    std.debug.print(
        "browser package: generated/tables.ts, generated/config.ts (v{s}, ingress {s})\n",
        .{ version, ingress_url },
    );
}

/// Version string read from a package.json document.
pub fn packageVersion(alloc: std.mem.Allocator, json: []const u8) ![]const u8 {
    var parsed = try std.json.parseFromSlice(std.json.Value, alloc, json, .{});
    defer parsed.deinit();
    const version = parsed.value.object.get("version") orelse return error.MissingVersion;
    return try alloc.dupe(u8, version.string);
}

/// Body of generated/tables.ts — `as const` tables and literal-union types
/// derived from model.FeatureID / model.FeatureType. Skips the internal
/// `Count` sentinel.
pub fn buildTables(alloc: std.mem.Allocator) ![]const u8 {
    var out = std.ArrayList(u8).init(alloc);
    errdefer out.deinit();
    const writer = out.writer();

    try writer.writeAll(
        \\// AUTO-GENERATED from src/model/feature.zig by `zig build clients:browser`.
        \\// Single source of truth is the Zig model — do not edit by hand.
        \\
        \\export const FeatureID = {
        \\
    );
    const fid_fields = @typeInfo(model.FeatureID).@"enum".fields;
    inline for (fid_fields) |field| {
        if (comptime std.mem.eql(u8, field.name, "Count")) continue;
        try writer.print("\t{s}: {d},\n", .{ field.name, field.value });
    }
    try writer.writeAll(
        \\} as const;
        \\
        \\export type FeatureID = (typeof FeatureID)[keyof typeof FeatureID];
        \\
        \\export const FeatureType = {
        \\
    );
    const ftype_fields = @typeInfo(model.FeatureType).@"enum".fields;
    inline for (ftype_fields) |field| {
        try writer.print("\t{s}: {d},\n", .{ field.name, field.value });
    }
    try writer.writeAll(
        \\} as const;
        \\
        \\export type FeatureType = (typeof FeatureType)[keyof typeof FeatureType];
        \\
    );
    return out.toOwnedSlice();
}

/// Body of generated/config.ts — SDK version and default ingress URL.
pub fn buildConfig(alloc: std.mem.Allocator, version: []const u8, ingress_url: []const u8) ![]const u8 {
    return std.fmt.allocPrint(alloc,
        \\// AUTO-GENERATED by `zig build clients:browser`.
        \\
        \\export const SDK_VERSION = "{s}";
        \\
        \\export const DEFAULT_INGRESS_URL = "{s}";
        \\
    , .{ version, ingress_url });
}

fn writeGenerated(
    alloc: std.mem.Allocator,
    package_dir: []const u8,
    name: []const u8,
    contents: []const u8,
) !void {
    // generated/ lives under the tsconfig rootDir so tsc emits dist/index.js
    // at the package top level (DESIGN §9.4.1).
    const generated_dir = try std.fs.path.join(alloc, &.{ package_dir, "src", "generated" });
    defer alloc.free(generated_dir);
    try std.fs.cwd().makePath(generated_dir);
    const path = try std.fs.path.join(alloc, &.{ generated_dir, name });
    defer alloc.free(path);
    try std.fs.cwd().writeFile(.{ .sub_path = path, .data = contents });
}
